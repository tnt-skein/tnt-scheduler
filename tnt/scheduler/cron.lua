--- Выражение cron: разбор роком `cron-parser` и следующий срок после мига.
---
--- Своего разбора cron в пакете нет: поля, диапазоны, шаги и имена дней
--- разбирает библиотека ccronexpr из рока, и второй разбор рядом с ней
--- расходился бы с тем, по которому ищется срок. Модуль
--- закрывает то, где рок молча ошибается или не умеет нужного. Всё ниже
--- сверено запуском на Tarantool 3.8 с роком `cron-parser 1.0.0-1`:
---
--- - число поля рок читает `strtol` с основанием 0: `010` в поле часа —
---   восьмеричное восемь, а `08` — отказ «Unsigned integer parse error».
---   Ведущие нули снимаются до рока, и `08` значит восемь, как в crontab;
--- - поля рок делит только пробелом, а прочие пробельные знаки выбрасывает
---   из поля: табуляция склеивает `0` и `0` в `00`, и расписание молча
---   сдвигается на поле. Всякий пробельный знак сводится к одному пробелу;
--- - полей у рока ровно шесть, секунды первыми. Запись crontab из пяти
---   полей получает нулевую секунду впереди; слов `@daily` и соседей рок
---   не знает — они переводятся таблицей;
--- - строку от 256 байт рок отвергает словами «must consist of 6 fields»,
---   хотя полей может быть и шесть, — длина проверяется здесь и называется;
--- - `cron.next` рока считает срок только от `os.time()`: срок от заданного
---   мига ему не посчитать, и часы-двойник проверке не подставить. Поэтому
---   `cron_next` библиотеки рока зовётся напрямую, а разобранное выражение
---   для него собирается `cron_parse_expr` той же библиотеки. Объявления
---   ffi рок делает сам при загрузке, и повторное объявление было бы
---   отказом «attempt to redefine»;
--- - `cron_next` на выражении, которое не разобралось (пустом или
---   разобранном до середины), **роняет процесс**: рекурсия поиска срока
---   переполняет стек — «Bus error», сверено запуском. Поэтому разбор идёт
---   дважды: годность и слова отказа даёт открытый `cron.parse` рока,
---   и только после его «да» выражение разбирается в структуру для поиска;
--- - срока, которого нет четыре года вперёд («30 февраля», а у 29 февраля —
---   с 2096 по 2100 год), рок не находит и отдаёт `-1`, то есть
---   1969-12-31 23:59:59, без проверки. Здесь это пустота.
---
--- Время рок считает в UTC (собран без `CRON_USE_LOCAL_TIME`): пояс
--- расписания — забота `tnt.scheduler.schedule`.

local ffi = require('ffi')

-- Рок объявляет при загрузке `cron_expr`, `cron_parse_expr` и `cron_next`.
local rock = require('cron')

--- Библиотека рока: та же, что загрузил сам рок.
local library = ffi.load(package.search('cron.ccronexpr'))

local Module = {}

--- Слова crontab, которых рок не знает, и их запись в шесть полей.
local WORDS = {
    ['@yearly'] = '0 0 0 1 1 *',
    ['@annually'] = '0 0 0 1 1 *',
    ['@monthly'] = '0 0 0 1 * *',
    ['@weekly'] = '0 0 0 * * 0',
    ['@daily'] = '0 0 0 * * *',
    ['@midnight'] = '0 0 0 * * *',
    ['@hourly'] = '0 0 * * * *',
}

--- Сколько полей у записи crontab без секунд.
local CLASSIC_FIELDS = 5

--- Самое длинное выражение, которое рок ещё делит на поля: от 256 байт
--- он отказывает, не называя длины.
Module.MAX_LENGTH = 255

--- Ответ рока «срока нет»: `CRON_INVALID_INSTANT`.
local NEVER = -1

--- Запись, которую рок прочтёт так, как её прочёл бы человек.
---
--- Ведущие нули снимаются образцом с границей `%f[%d]`: он видит начало
--- числа, а не цифру внутри него, — `10` и `100` остаются собой. Нули
--- впереди записаны `0[0]*`, а не `0+` и не `00*`: `0*` на их месте снимал
--- бы те же нули (число без нуля впереди заменялось бы само собой), и порчу
--- образца такой подменой не заметила бы ни одна проверка.
---@param text string
---@return string
function Module.normalize(text)
    local spaced = text:gsub('%s+', ' ')
    local trimmed = spaced:match('^ ?(.-) ?$') --[[@as string]]
    local word = WORDS[trimmed:lower()]

    if word ~= nil then
        return word
    end

    local decimal = trimmed:gsub('%f[%d]0[0]*(%d)', '%1')
    local _, fields = decimal:gsub('%S+', '')

    if fields == CLASSIC_FIELDS then
        return '0 ' .. decimal
    end

    return decimal
end

--- Разбирает выражение роком.
---
--- Отказ рока — его собственные слова: они называют поле и беду точнее
--- любого пересказа («Specified range exceeds maximum»).
---
--- Структура для поиска — одна, а не массив из одной, как у рока: размер
--- массива в строке типа был бы числом, которое можно поменять незаметно
--- для любой проверки, — больший массив работает так же.
---@param text string
---@return ffi.cdata*|nil compiled Разобранное выражение
---@return string|nil err
function Module.compile(text)
    local expression = Module.normalize(text)

    if #expression > Module.MAX_LENGTH then
        return nil, ('длиннее %d байт'):format(Module.MAX_LENGTH)
    end

    local parsed, err = rock.parse(expression)

    if parsed == nil then
        return nil, err
    end

    local compiled = ffi.new('cron_expr')

    library.cron_parse_expr(expression, compiled, nil)

    return compiled
end

--- Ближайший срок строго после мига, в секундах UTC.
---
--- Миг целый: `time_t` рока дробей не знает, а срок, совпавший с мигом,
--- рок пропускает и ищет следующий.
---@param compiled ffi.cdata* Разобранное выражение
---@param moment number Секунды от начала эпохи, целые
---@return number|nil fire Пустота — срока нет четыре года вперёд
function Module.after(compiled, moment)
    local fire = tonumber(library.cron_next(compiled, moment))

    if fire == NEVER then
        return nil
    end

    return fire
end

return Module
